package Muaaz;

public class Week6_1_OddNumbers1To99 {
    public static void main(String[] args) {
        System.out.println("Odd numbers between 1 and 99 are:");

        for (int number = 1; number <= 99; number = number + 2) {
            System.out.print(number + " ");
        }

        System.out.println();
    }
}
